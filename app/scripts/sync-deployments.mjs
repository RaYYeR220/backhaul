#!/usr/bin/env node
// Writes src/lib/deployments.ts from ../deployments/{portaldot,bsc}.json and the ABI fragments the
// app calls from a visitor's wallet. ABIs come from the forge artifacts when they are built
// (contracts/out, contracts/out-portaldot) and otherwise from packages/sdk/src/abi.ts, which is
// generated from the same artifacts. Run it after every deploy:
//
//   npm run sync:deployments
//
// With no deployment files it writes a "not deployed yet" module that the app handles.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../..");
const out = resolve(here, "../src/lib/deployments.ts");

/** Contract → the functions and events the app needs from it. */
const NEEDS = {
  PortaldotGateway: { sdk: "portaldotGatewayAbi", items: ["lockPOT", "burnBNBb", "FEE_BPS", "Locked"] },
  BscGateway: { sdk: "bscGatewayAbi", items: ["lockBNB", "burnPPOT", "Locked"] },
  ERC20: { sdk: "erc20Abi", items: ["approve", "allowance", "balanceOf"] },
};

function fromArtifacts(name) {
  for (const dir of ["contracts/out", "contracts/out-portaldot"]) {
    const p = resolve(repo, dir, `${name}.sol`, `${name}.json`);
    if (existsSync(p)) return { abi: JSON.parse(readFileSync(p, "utf8")).abi, source: `${dir}/${name}.sol/${name}.json` };
  }
  return null;
}

let sdkAbis;
function fromSdk(exportName) {
  if (!sdkAbis) {
    sdkAbis = {};
    const p = resolve(repo, "packages/sdk/src/abi.ts");
    if (!existsSync(p)) return null;
    for (const line of readFileSync(p, "utf8").split(/\r?\n/)) {
      const m = /^export const (\w+) = (\[.*\]) as const;$/.exec(line);
      if (m) sdkAbis[m[1]] = JSON.parse(m[2]);
    }
  }
  return sdkAbis[exportName] ? { abi: sdkAbis[exportName], source: "packages/sdk/src/abi.ts" } : null;
}

const abis = {};
const sources = {};
for (const [name, need] of Object.entries(NEEDS)) {
  const found = fromArtifacts(name) ?? fromSdk(need.sdk);
  if (!found) throw new Error(`no ABI for ${name}: build the contracts (forge build) or generate packages/sdk/src/abi.ts`);
  const picked = need.items.map((item) => {
    const f = found.abi.find((x) => x.name === item && (x.type === "function" || x.type === "event"));
    if (!f) throw new Error(`${name} has no ${item} in ${found.source}`);
    return f;
  });
  abis[name] = picked;
  sources[name] = found.source;
}

function loadDeployment(chain, chainId) {
  const p = resolve(repo, "deployments", `${chain}.json`);
  if (!existsSync(p)) return null;
  const d = JSON.parse(readFileSync(p, "utf8"));
  if (d.chainId !== chainId) throw new Error(`${p} is for chain ${d.chainId}, not ${chainId}`);
  const contracts = Object.fromEntries(Object.entries(d.contracts ?? {}).map(([k, v]) => [k, v.address]));
  return { chainId, updatedAt: d.updatedAt ?? null, contracts, meta: d.meta ?? {} };
}

const pd = loadDeployment("portaldot", 420420777);
const bsc = loadDeployment("bsc", 97);

const deployments = {
  portaldot: pd && pd.contracts.PortaldotGateway
    ? { chainId: pd.chainId, updatedAt: pd.updatedAt, gateway: pd.contracts.PortaldotGateway, bnbb: pd.meta.bnbb?.precompile ?? null, contracts: pd.contracts }
    : null,
  bsc: bsc && bsc.contracts.BscGateway
    ? { chainId: bsc.chainId, updatedAt: bsc.updatedAt, gateway: bsc.contracts.BscGateway, ppot: bsc.contracts.PPOT ?? null, contracts: bsc.contracts }
    : null,
};

const json = (v) => JSON.stringify(v, null, 2);
const ts = `// Generated by scripts/sync-deployments.mjs from deployments/*.json and the contract ABIs
// (${[...new Set(Object.values(sources))].join(", ")}). Do not edit; run \`npm run sync:deployments\`.

export interface ChainDeployment {
  chainId: number;
  updatedAt: string | null;
  /** The canonical gateway a wallet calls to lock or burn. */
  gateway: \`0x\${string}\`;
  contracts: Record<string, \`0x\${string}\`>;
}

export interface Deployments {
  /** null until the Portaldot side is deployed. */
  portaldot: (ChainDeployment & { bnbb: \`0x\${string}\` | null }) | null;
  /** null until the BNB Chain side is deployed. */
  bsc: (ChainDeployment & { ppot: \`0x\${string}\` | null }) | null;
}

export const deployments: Deployments = ${json(deployments)};

export const portaldotGatewayAbi = ${json(abis.PortaldotGateway)} as const;

export const bscGatewayAbi = ${json(abis.BscGateway)} as const;

export const erc20Abi = ${json(abis.ERC20)} as const;
`;

writeFileSync(out, ts);
const state = (d) => (d ? `deployed (gateway ${d.gateway})` : "not deployed yet");
console.log(`wrote ${out}\n  portaldot: ${state(deployments.portaldot)}\n  bsc: ${state(deployments.bsc)}`);
