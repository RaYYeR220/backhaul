/**
 * Writes packages/sdk/src/abi.ts from the forge artifacts, so the relayer and the app get typed
 * ABIs without a build of the contracts.
 *
 *   (cd contracts && forge build) && npx tsx packages/sdk/scripts/gen-abi.ts [--check]
 *
 * `--check` exits non-zero if abi.ts is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadArtifact } from '../src/artifacts.js';

export const ABI_CONTRACTS = [
  'Outbox',
  'PortaldotLightClient',
  'PortaldotVerifier',
  'PPOT',
  'BscGateway',
  'PortaldotGateway',
  'ParliaClient',
  'BscVerifier',
  'BscFeed',
  'OriginSettler',
  'DestinationSettler',
  'LPVault',
  'PortaldotRepayForwarder',
  'BscRepayForwarder',
  'ERC20',
] as const;

const camel = (n: string) => n.replace(/^[A-Z0-9]+(?=[A-Z][a-z]|$)|^[A-Z]/, (m) => m.toLowerCase());

export function renderAbiModule(): string {
  const lines = [
    '// Generated by packages/sdk/scripts/gen-abi.ts from the forge artifacts. Do not edit.',
    '',
  ];
  const names: string[] = [];
  const errors = new Map<string, unknown>();
  for (const c of ABI_CONTRACTS) {
    const abi = loadArtifact(c).abi;
    const id = `${camel(c)}Abi`;
    names.push(id);
    lines.push(`export const ${id} = ${JSON.stringify(abi)} as const;`, '');
    for (const item of abi) {
      if (item.type !== 'error') continue;
      const sig = `${item.name}(${item.inputs.map((i) => i.type).join(',')})`;
      if (!errors.has(sig)) errors.set(sig, item);
    }
  }
  lines.push(
    '/** Every custom error any Backhaul contract (or a library inside it) can revert with. */',
    `export const backhaulErrorsAbi = ${JSON.stringify([...errors.values()])} as const;`,
    '',
  );
  return lines.join('\n');
}

const out = resolve(import.meta.dirname, '../src/abi.ts');
const text = renderAbiModule();
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error('src/abi.ts is out of date; run scripts/gen-abi.ts');
    process.exit(1);
  }
  console.log('src/abi.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
